use serde::{Deserialize, Serialize};
use sqlx::FromRow;

#[derive(Debug, Serialize, Deserialize, FromRow)]
#[serde(rename_all = "PascalCase")]
#[sqlx(rename_all = "PascalCase")]
pub struct CSMiniGameRelayServerInfo {
    #[sqlx(rename = "Index")]
    pub index: i64,
    #[sqlx(rename = "Uid")]
    pub uid: i64,
    #[sqlx(rename = "HeaderIndex")]
    pub header_index: Option<i64>,
    #[sqlx(rename = "ServerInfoIndex")]
    pub server_info_index: Option<String>,
}